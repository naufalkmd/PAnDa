#!/usr/bin/env bash
# Create the project environment in .venv (Linux or WSL, Python 3.12, NVIDIA GPU with CUDA 12.8 drivers).
# Run from the repository root:
#   bash scripts/setup_env.sh          # exact versions from requirements-lock.txt (reproduce)
#   bash scripts/setup_env.sh --lock   # resolve requirements.txt, then rewrite requirements-lock.txt
# The environment does not use system site-packages, so nothing outside .venv changes the results.
set -euo pipefail

PYTHON="${PYTHON:-python3.12}"
MODE="${1:-}"

if [ -e .venv ]; then
  echo ".venv already exists; move or delete it first." >&2
  exit 1
fi

"$PYTHON" -m venv .venv
./.venv/bin/python -m pip install --upgrade pip

if [ "$MODE" = "--lock" ]; then
  ./.venv/bin/pip install -r requirements.txt
  {
    echo "# Generated by scripts/setup_env.sh --lock on $(date -u +%Y-%m-%d) from requirements.txt. Do not edit."
    echo "--extra-index-url https://download.pytorch.org/whl/cu128"
    ./.venv/bin/pip freeze --exclude-editable
  } > requirements-lock.txt
  echo "Wrote requirements-lock.txt"
else
  ./.venv/bin/pip install -r requirements-lock.txt
fi

# The project itself, without letting pip change any pinned dependency.
./.venv/bin/pip install --no-deps -e .

./.venv/bin/python - <<'EOF'
import torch, transformers, datasets, huggingface_hub
print("torch", torch.__version__, "| cuda", torch.version.cuda, "| gpu",
      torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none")
print("transformers", transformers.__version__, "| datasets", datasets.__version__,
      "| huggingface_hub", huggingface_hub.__version__)
EOF
