"""Write the report's tables as LaTeX (booktabs) into paper/tables/ from the results files. No GPU, no download.

Run from the repository root:
    python scripts/report_tables.py

Every cell is read from a results CSV of exp19, exp20 or exp21 (paths below) and only formatted here: 3 decimals,
signed differences, 95 % intervals in brackets, p-values below 0.001 as "<0.001". The report \\input{}s each file
inside its table float, so a rerun of an analysis updates the tables without hand editing.

    t1_heldout.tex          exp19 scores_by_split.csv, heldout_main.csv
    t2_factorial.tex        exp19 scores_by_split.csv, heldout_factorial.csv
    t3_interval.tex         exp19 scores_by_split.csv, heldout_interval.csv
    t4_masking.tex          exp19 mask_counts.csv
    t5_length.tex           exp19 length_control.csv, length_association.csv
    t6_selfeval.tex         exp20 run_01 and run_02 analysis/scores.csv
    t7_selfeval_tests.tex   exp20 run_02 analysis/paired_tests.csv
    t8_selective.tex        exp20 run_02 analysis/selective_prediction.csv
    t9_early_exit.tex       exp20 cross_model/early_exit_selection.csv
    t10_question_removed.tex exp20 cross_model/prior_correction.csv
    t11_vs_likelihood.tex   exp20 cross_model/self_evaluation_vs_likelihood.csv (exp21 scores)
"""
from __future__ import annotations

