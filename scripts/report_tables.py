def rows(path: Path) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def num(x) -> str:
    return f"{float(x):.3f}"


def signed(x) -> str:
    x = float(x)
    return f"${'+' if x >= 0 else '-'}{abs(x):.3f}$"


def interval(lo, hi) -> str:
    return f"[{signed(lo)}, {signed(hi)}]"


def pval(p) -> str:
    if p in ("", None):
        return "--"
    p = float(p)
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def yes(flag) -> str:
    return "yes" if str(flag) == "True" else "no"


def write(name: str, colspec: str, header: list[str], body: list[list[str]], midrules: tuple[int, ...] = ()) -> None:
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", *header, "\\midrule"]
    for i, r in enumerate(body):
        if i in midrules:
            lines.append("\\midrule")
        lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("% Generated by scripts/report_tables.py from the results files; do not edit by hand.\n"
                            + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote paper/tables/{name}")


def pair(table: list[dict], a: str, b: str, metric: str) -> dict:
    return next(r for r in table if r["pair"] == f"{a}:{b}" and r["metric"] == metric)


def t1() -> None:
    scores = {r["decoder"]: r for r in rows(A19 / "scores_by_split.csv")}
    tests = rows(A19 / "heldout_main.csv")
    body = []
    for d, label in (("pure_greedy", "Base likelihood"), ("dola_mc_reference", "DoLa (MC configuration)"),
                     ("dola", "DoLa (generation settings)"), ("fanda_frozen", "Per-question DoLa-static")):
        s = scores[d]
        r = [label] + [num(s[f"dev_{m}"]) for m in ("mc1", "mc2", "mc3")] + [num(s[f"heldout_{m}"]) for m in ("mc1", "mc2", "mc3")]
        if d == "pure_greedy":
            r += ["--", "--", "--"]
        else:
            t = pair(tests, d, "pure_greedy", "mc1")
            r += [f"{signed(t['diff'])} {interval(t['ci_low'], t['ci_high'])}", f"{t['mcnemar_b']}/{t['mcnemar_c']}",
                  pval(t["p_mcnemar_holm"])]
        body.append(r)
    write("t1_heldout.tex", "lcccccccll",
          ["& \\multicolumn{3}{c}{Development (50)} & \\multicolumn{3}{c}{Held-out (767)} & \\multicolumn{3}{c}{Held-out MC1 minus base likelihood} \\\\",
           "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7} \\cmidrule(lr){8-10}",
           "Rule & MC1 & MC2 & MC3 & MC1 & MC2 & MC3 & Difference [95\\,\\% interval] & Gained/lost & $p$ \\\\"], body)


def t2() -> None:
    scores = {r["decoder"]: r for r in rows(A19 / "scores_by_split.csv")}
    tests = rows(A19 / "heldout_factorial.csv")
    spec = (  # (decoder, constraint, difference, layer, compared with)
        ("dola", "yes", "log-probability", "every token", None),
        ("exp13_logit_top", "yes", "raw logit", "every token", ("exp13_logit_top", "exp13_logprob_top")),
        ("exp13_logprob_no_top", "no", "either", "every token", ("exp13_logprob_no_top", "exp13_logprob_top")),
        ("fanda_frozen", "no", "raw logit", "once per question", ("fanda_frozen", "exp13_logprob_no_top")),
    )
    body = []
    for d, c, diff, layer, cmp in spec:
        s = scores[d]
        r = [c, diff, layer] + [num(s[f"heldout_{m}"]) for m in ("mc1", "mc2", "mc3")]
        if cmp is None:
            r += ["--", "--"]
        else:
            t = pair(tests, cmp[0], cmp[1], "mc1")
            r += [f"{signed(t['diff'])} {interval(t['ci_low'], t['ci_high'])}", pval(t["p_mcnemar_holm"])]
        body.append(r)
    write("t2_factorial.tex", "lllccccl",
          ["Constraint & Difference & Layer chosen & MC1 & MC2 & MC3 & MC1 minus the row above [95\\,\\% interval] & $p$ \\\\"],
          body)


