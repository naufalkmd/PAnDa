def t6() -> None:
    conf = {r["rule"]: r for r in rows(CONF / "scores.csv")}
    expl = {r["rule"]: r for r in rows(EXPL / "scores.csv")}
    body = []
    for key, label in SELF_RULES:
        c, e = conf[key], expl[key]
        body.append([label, num(e["mc1"]), num(c["mc1"]), num(c["mc2"]) if c["mc2"] else "--", num(c["mc3"]),
                     num(c["pairwise_accuracy_length_matched"]), signed(c["spearman_with_token_count"])])
    write("t6_selfeval.tex", "lcccccc",
          ["& Exploration (417) & \\multicolumn{5}{c}{Confirmation (400)} \\\\", "\\cmidrule(lr){2-2} \\cmidrule(lr){3-7}",
           "Rule & MC1 & MC1 & MC2 & MC3 & Matched pairs & Length correlation \\\\"],
          body, midrules=(3,))


def t7() -> None:
    labels = dict(SELF_RULES)
    tests = rows(CONF / "paired_tests.csv")
    body = []
    for r in tests:
        if r["metric"] != "mc1":
            continue
        m2 = next(x for x in tests if x["a"] == r["a"] and x["b"] == r["b"] and x["metric"] == "mc2")
        m3 = next(x for x in tests if x["a"] == r["a"] and x["b"] == r["b"] and x["metric"] == "mc3")
        other = labels[r["b"]]
        other = other[0].lower() + other[1:] if other.startswith(("Base", "Self", "Longest", "Per")) else other
        body.append([f"{labels[r['a']]} minus {other}",
                     f"{signed(r['diff'])} {interval(r['ci_low'], r['ci_high'])}", f"{r['mcnemar_b']}/{r['mcnemar_c']}",
                     pval(r["p_mcnemar_holm"]), signed(m2["diff"]), signed(m3["diff"])])
    write("t7_selfeval_tests.tex", "p{6.2cm}lccrr",
          ["Comparison & MC1 difference [95\\,\\% interval] & Gained/lost & $p$ & MC2 & MC3 \\\\"], body, midrules=(3,))


def t8() -> None:
    table = rows(CONF / "selective_prediction.csv")
    total = int(next(r for r in table if r["kind"] == "all questions")["answered"])
    body = []
    for r in table:
        if r["kind"].startswith("frozen"):
            answered = int(r["answered"])
            body.append([f"{100 * float(r['coverage_target']):.0f}\\,\\%", f"{answered} of {total}",
                         f"{(1000 * answered + total // 2) // total / 10:.1f}\\,\\%",  # round half up
                         num(r["selective_accuracy"]), interval(r["ci_low"], r["ci_high"]).replace("$+", "$")])
    r = next(r for r in table if r["kind"] == "all questions")
    body.append(["none (answer all)", f"{total} of {total}", "100.0\\,\\%", num(r["selective_accuracy"]), "--"])
    write("t8_selective.tex", "lcccc",
          ["Threshold set for coverage & Answered & Coverage & MC1 on the answered questions & 95\\,\\% interval \\\\"],
          body, midrules=(3,))


